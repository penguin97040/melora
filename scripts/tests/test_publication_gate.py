import json
from pathlib import Path
import subprocess
import tempfile
import unittest

GATE = Path(__file__).resolve().parents[1] / 'publication_gate.py'

class PublicationTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.run_git('init', '-q')
        self.run_git('config', 'user.name', 'Melora Maintainer')
        self.run_git('config', 'user.email', '1+fixture' + '@users.noreply.github.com')
        self.run_git('remote', 'add', 'origin', 'https://github.com/fixture/melora.git')
        (self.root / '.git/melora-publication.json').write_text(json.dumps({
            'remote': 'https://github.com/fixture/melora.git', 'name': 'Melora Maintainer',
            'email': '1+fixture' + '@users.noreply.github.com'}))

    def run_git(self, *args, **kwargs):
        return subprocess.run(['git', *args], cwd=self.root, check=True, capture_output=True, **kwargs)

    def gate(self, *args, input=None):
        return subprocess.run(['python3', str(GATE), *args], cwd=self.root, capture_output=True, text=True, input=input)

    def test_clean_placeholder(self):
        (self.root / '.env.example').write_text('VITE_SPOTIFY_CLIENT_ID=YOUR_SPOTIFY_CLIENT_ID\n')
        self.assertEqual(self.gate().returncode, 0)

    def test_fixtures_do_not_leak_values(self):
        fixtures = [
            ('src.txt', 'ghp_' + 'X' * 36),
            ('src.txt', 'refresh_token="' + 'S' * 50 + '"'),
            ('src.txt', 'GITHUB_TOKEN="' + 'Q' * 40 + '"'),
            ('AGENTS.md', 'private fixture'),
            ('src.txt', 'Generated by ' + 'AI'),
            ('src.txt', 'someone' + '@personal.invalid'),
            ('artifacts/file.txt', 'build fixture'),
        ]
        for path, value in fixtures:
            with self.subTest(path=path, value_type=len(value)):
                file = self.root / path
                file.parent.mkdir(parents=True, exist_ok=True)
                file.write_text(value)
                result = self.gate()
                self.assertNotEqual(result.returncode, 0)
                self.assertNotIn(value, result.stdout + result.stderr)
                file.unlink()

    def test_deleted_historical_secret(self):
        secret = 'ghp_' + 'Z' * 36
        (self.root / 'example.txt').write_text(secret)
        self.run_git('add', '.')
        self.run_git('commit', '-qm', 'Add fixture')
        (self.root / 'example.txt').write_text('clean')
        self.run_git('commit', '-qam', 'Remove fixture')
        result = self.gate()
        self.assertNotEqual(result.returncode, 0)
        self.assertNotIn(secret, result.stderr)

    def test_commit_message_and_identity(self):
        (self.root / 'example.txt').write_text('clean')
        self.run_git('add', '.')
        self.run_git('commit', '-qm', 'Generated by ' + 'AI')
        self.assertNotEqual(self.gate().returncode, 0)
        self.run_git('commit', '--amend', '-qm', 'Clean fixture', '--author=Other <other' + '@invalid.test>')
        self.assertNotEqual(self.gate().returncode, 0)

    def test_staged_secret_clean_working_copy(self):
        secret = 'ghp_' + 'Y' * 36
        (self.root / 'example.txt').write_text(secret)
        self.run_git('add', '.')
        (self.root / 'example.txt').write_text('clean')
        self.assertNotEqual(self.gate().returncode, 0)

    def test_fail_closed(self):
        (self.root / '.git/melora-publication.json').unlink()
        self.assertNotEqual(self.gate().returncode, 0)

    def test_hook_destination_and_malformed_input(self):
        self.assertNotEqual(self.gate('--hook', 'other', 'https://github.com/fixture/melora.git', input='').returncode, 0)
        self.assertNotEqual(self.gate('--hook', 'origin', 'https://github.com/fixture/melora.git', input='broken').returncode, 0)

    def test_sensitive_filename_is_blocked_without_disclosure(self):
        secret = 'ghp_' + 'F' * 36
        (self.root / (secret + '.txt')).write_text('synthetic data')
        result = self.gate()
        self.assertNotEqual(result.returncode, 0)
        self.assertNotIn(secret, result.stdout + result.stderr)
        self.assertIn('redacted path', result.stderr)

    def test_additional_push_destination_is_blocked(self):
        self.run_git('config', '--add', 'remote.origin.pushurl', 'https://github.com/fixture/melora.git')
        self.run_git('config', '--add', 'remote.origin.pushurl', 'https://github.com/fixture/other.git')
        self.assertNotEqual(self.gate().returncode, 0)

    def test_invalid_approval_types_fail_closed_without_traceback(self):
        approval = self.root / '.git/melora-publication.json'
        for data in [[], {'remote': [], 'name': 'fixture', 'email': 1}]:
            approval.write_text(json.dumps(data))
            result = self.gate()
            self.assertNotEqual(result.returncode, 0)
            self.assertNotIn('Traceback', result.stderr)

    def test_hook_rejects_invalid_object_ids_including_deletions(self):
        destination = 'https://github.com/fixture/melora.git'
        for value in ['0', 'HEAD', 'HEAD~1', 'Z' * 40]:
            line = f'refs/heads/main {value} refs/heads/main {"0" * 40}\n'
            self.assertNotEqual(self.gate('--hook', 'origin', destination, input=line).returncode, 0)

    def test_extra_commit_metadata_is_scanned(self):
        (self.root / 'example.txt').write_text('synthetic data')
        self.run_git('add', '.')
        self.run_git('commit', '-qm', 'Add fixture')
        raw = self.run_git('cat-file', 'commit', 'HEAD').stdout
        secret = 'ghp_' + 'M' * 36
        headers, body = raw.split(b'\n\n', 1)
        commit = headers + b'\nencoding ' + secret.encode() + b'\n\n' + body
        oid = self.run_git('hash-object', '-t', 'commit', '-w', '--stdin', input=commit).stdout.strip()
        self.run_git('update-ref', 'refs/heads/main', oid.decode())
        self.run_git('symbolic-ref', 'HEAD', 'refs/heads/main')
        result = self.gate()
        self.assertNotEqual(result.returncode, 0)
        self.assertNotIn(secret, result.stdout + result.stderr)

    def test_standard_retina_icon_filename_still_scans_contents(self):
        icon = self.root / 'src-tauri/icons' / ('128x128' + '@' + '2x.png')
        icon.parent.mkdir(parents=True)
        icon.write_text('Synthetic icon fixture')
        self.assertEqual(self.gate().returncode, 0)
        icon.write_text('ghp_' + 'I' * 36)
        self.assertNotEqual(self.gate().returncode, 0)
